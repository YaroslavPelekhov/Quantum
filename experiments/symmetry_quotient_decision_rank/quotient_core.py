def triangle_symmetry_generators(
    triangles: int, ring: bool, order: list[int]
) -> list[np.ndarray]:
    """Generators of leaf swaps and chain/ring dihedral triangle symmetries."""
    qubits = 3 * triangles
    position = {vertex: index for index, vertex in enumerate(order)}

    def position_permutation(vertex_map: dict[int, int]) -> np.ndarray:
        result = np.arange(qubits, dtype=int)
        for old_vertex, new_vertex in vertex_map.items():
            result[position[old_vertex]] = position[new_vertex]
        return result

    generators = []
    for triangle in range(triangles):
        mapping = {vertex: vertex for vertex in range(qubits)}
        left, right = 3 * triangle + 1, 3 * triangle + 2
        mapping[left], mapping[right] = right, left
        generators.append(position_permutation(mapping))

    if ring:
        rotation = {}
        reflection = {}
        for triangle in range(triangles):
            for offset in range(3):
                vertex = 3 * triangle + offset
                rotation[vertex] = 3 * ((triangle + 1) % triangles) + offset
                reflection[vertex] = 3 * ((-triangle) % triangles) + offset
        generators.extend((
            position_permutation(rotation), position_permutation(reflection)
        ))
    else:
        reflection = {}
        for triangle in range(triangles):
            for offset in range(3):
                reflection[3 * triangle + offset] = (
                    3 * (triangles - 1 - triangle) + offset
                )
        generators.append(position_permutation(reflection))
    return generators


def permutation_index_map(qubits: int, position_map: np.ndarray) -> np.ndarray:
    """Map every integer basis index under an old-position -> new-position map."""
    indices = np.arange(1 << qubits, dtype=np.uint32)
    mapped = np.zeros_like(indices)
    for old, new in enumerate(np.asarray(position_map, dtype=int)):
        mapped |= ((indices >> old) & 1) << int(new)
    return mapped


def orbit_labels(qubits: int, generators: list[np.ndarray]) -> tuple[np.ndarray, np.ndarray]:
    """Return connected components of the basis action generated by permutations."""
    dimension = 1 << qubits
    source = np.arange(dimension, dtype=np.int32)
    rows = np.tile(source, len(generators))
    columns = np.concatenate([
        permutation_index_map(qubits, generator).astype(np.int32)
        for generator in generators
    ])
    action = coo_matrix(
        (np.ones(rows.size, dtype=np.int8), (rows, columns)),
        shape=(dimension, dimension),
    ).tocsr()
    count, labels = connected_components(action, directed=False, return_labels=True)
    sizes = np.bincount(labels, minlength=count).astype(np.int64)
    return labels.astype(np.int32), sizes


def quotient_mixer(labels: np.ndarray, sizes: np.ndarray, qubits: int) -> csr_matrix:
    """Matrix of sum_i X_i in the normalized orbit basis."""
    # Equitability of a group orbit partition means a single representative is
    # enough to count neighbors from an orbit into every other orbit.  This
    # avoids enumerating n*2^n hypercube edges after the orbit labels exist.
    orbit_count = sizes.size
    _, representatives = np.unique(labels, return_index=True)
    representatives = representatives.astype(np.uint32)
    rows = []
    columns = []
    values = []
    for qubit in range(qubits):
        source = np.arange(orbit_count, dtype=np.int32)
        target = labels[representatives ^ np.uint32(1 << qubit)]
        rows.append(source)
        columns.append(target)
        values.append(np.sqrt(sizes[source] / sizes[target]))
    row = np.concatenate(rows)
    column = np.concatenate(columns)
    weights = np.concatenate(values)
    mixer = coo_matrix(
        (weights, (row, column)), shape=(orbit_count, orbit_count)
    ).tocsr()
    mixer.sum_duplicates()
    return mixer


@dataclass(frozen=True)
class QuotientArchitecture:
    qubits: int
    labels: np.ndarray
    sizes: np.ndarray
    mixer: csr_matrix
    orbit_energy: np.ndarray

    @property
    def orbit_count(self) -> int:
        return int(self.sizes.size)


@dataclass(frozen=True)
class QuotientState:
    architecture: QuotientArchitecture
    coefficients: np.ndarray

    def amplitudes(self, indices: np.ndarray) -> np.ndarray:
        labels = self.architecture.labels[np.asarray(indices, dtype=np.int64)]
        return self.coefficients[labels] / np.sqrt(self.architecture.sizes[labels])

    def dense(self) -> np.ndarray:
        return self.amplitudes(np.arange(self.architecture.labels.size))


def twin_classes(graph, order: list[int]) -> list[list[int]]:
    """Partition qubit positions into maximal true/false-twin classes."""
    nodes = list(order)
    remaining = set(nodes)
    classes = []
    while remaining:
        anchor = min(remaining)
        group = []
        anchor_neighbors = set(graph.neighbors(anchor))
        for candidate in sorted(remaining):
            candidate_neighbors = set(graph.neighbors(candidate))
            if (
                anchor_neighbors - {candidate}
                == candidate_neighbors - {anchor}
            ):
                group.append(candidate)
        for node in group:
            remaining.remove(node)
        classes.append(sorted(order.index(node) for node in group))
    classes.sort(key=lambda group: min(group))
    return classes


@dataclass(frozen=True)
class TwinQuotientArchitecture:
    qubits: int
    groups: tuple[tuple[int, ...], ...]
    radices: tuple[int, ...]
    orbit_sizes: np.ndarray
    orbit_energy: np.ndarray
    mixer_eigenvectors: tuple[np.ndarray, ...]
    mixer_eigenvalues: tuple[np.ndarray, ...]

    @property
    def orbit_count(self) -> int:
        return int(self.orbit_sizes.size)


@dataclass(frozen=True)
class TwinQuotientState:
    architecture: TwinQuotientArchitecture
    coefficients: np.ndarray

    def amplitudes(self, indices: np.ndarray) -> np.ndarray:
        flat = np.asarray(indices, dtype=np.int64)
        shape = flat.shape
        values = flat.reshape(-1)
        digits = []
        for group in self.architecture.groups:
            count = np.zeros(values.size, dtype=np.int16)
            for qubit in group:
                count += ((values >> qubit) & 1).astype(np.int16)
            digits.append(count)
        labels = np.ravel_multi_index(tuple(digits), self.architecture.radices)
        amplitudes = (
            self.coefficients[labels]
            / np.sqrt(self.architecture.orbit_sizes[labels])
        )
        return amplitudes.reshape(shape)

    def dense(self) -> np.ndarray:
        return self.amplitudes(np.arange(1 << self.architecture.qubits))


def compile_twin_quotient(
    graph,
    order: list[int],
    penalty: float = 2.0,
    normalized_ising: bool = False,
) -> TwinQuotientArchitecture:
    """Compile a full symmetric-group quotient for graph twin classes."""
    groups = tuple(tuple(group) for group in twin_classes(graph, order))
    radices = tuple(len(group) + 1 for group in groups)
    configurations = np.indices(radices, dtype=np.int16).reshape(len(groups), -1)
    selected = configurations.sum(axis=0, dtype=np.int16)
    violations = np.zeros(configurations.shape[1], dtype=np.int16)
    position_to_group = {
        position: group_index
        for group_index, group in enumerate(groups)
        for position in group
    }
    node_to_position = {node: index for index, node in enumerate(order)}
    for left_group, group in enumerate(groups):
        if len(group) >= 2:
            nodes = [order[position] for position in group]
            if graph.has_edge(nodes[0], nodes[1]):
                count = configurations[left_group]
                violations += count * (count - 1) // 2
    for left_group in range(len(groups)):
        for right_group in range(left_group + 1, len(groups)):
            left_node = order[groups[left_group][0]]
            right_node = order[groups[right_group][0]]
            if graph.has_edge(left_node, right_node):
                violations += (
                    configurations[left_group] * configurations[right_group]
                )
    qubo_energy = -selected.astype(np.float64) + penalty * violations
    if normalized_ising:
        orbit_energy = qubo_energy * (4.0 / penalty)
    else:
        orbit_energy = selected.astype(np.float64) - penalty * violations
    orbit_sizes = np.ones(configurations.shape[1], dtype=np.int64)
    for group_index, group in enumerate(groups):
        orbit_sizes *= np.asarray(
            [comb(len(group), int(value)) for value in configurations[group_index]],
            dtype=np.int64,
        )
    eigenvectors = []
    eigenvalues = []
    for group in groups:
        size = len(group)
        local = np.zeros((size + 1, size + 1), dtype=np.float64)
        for count in range(size):
            coupling = np.sqrt((count + 1) * (size - count))
            local[count, count + 1] = coupling
            local[count + 1, count] = coupling
        values, vectors = linalg.eigh(local, check_finite=False)
        eigenvalues.append(values)
        eigenvectors.append(vectors)
    return TwinQuotientArchitecture(
        qubits=len(order), groups=groups, radices=radices,
        orbit_sizes=orbit_sizes, orbit_energy=orbit_energy,
        mixer_eigenvectors=tuple(eigenvectors),
        mixer_eigenvalues=tuple(eigenvalues),
    )


def _apply_axis_unitary(
    coefficients: np.ndarray,
    radices: tuple[int, ...],
    axis: int,
    unitary: np.ndarray,
) -> np.ndarray:
    tensor = coefficients.reshape(radices)
    moved = np.moveaxis(tensor, axis, 0)
    updated = unitary @ moved.reshape(radices[axis], -1)
    restored = np.moveaxis(updated.reshape(moved.shape), 0, axis)
    return np.ascontiguousarray(restored).reshape(-1)


def evolve_twin_quotient(
    architecture: TwinQuotientArchitecture,
    gammas: np.ndarray,
    betas: np.ndarray,
) -> TwinQuotientState:
    coefficients = np.sqrt(
        architecture.orbit_sizes / float(1 << architecture.qubits)
    ).astype(np.complex128)
    for gamma, beta in zip(gammas, betas, strict=True):
        coefficients *= np.exp(-1j * float(gamma) * architecture.orbit_energy)
        for axis, (vectors, values) in enumerate(zip(
            architecture.mixer_eigenvectors,
            architecture.mixer_eigenvalues,
            strict=True,
        )):
            unitary = (
                vectors * np.exp(-1j * float(beta) * values)[None, :]
            ) @ vectors.T
            coefficients = _apply_axis_unitary(
                coefficients, architecture.radices, axis, unitary
            )
    return TwinQuotientState(architecture, coefficients)


def compile_quotient(
    energy: np.ndarray, generators: list[np.ndarray]
) -> QuotientArchitecture:
    qubits = int(round(np.log2(energy.size)))
    labels, sizes = orbit_labels(qubits, generators)
    orbit_count = sizes.size
    minimum = np.full(orbit_count, np.iinfo(np.int16).max, dtype=np.int16)
    maximum = np.full(orbit_count, np.iinfo(np.int16).min, dtype=np.int16)
    np.minimum.at(minimum, labels, energy)
    np.maximum.at(maximum, labels, energy)
    if not np.array_equal(minimum, maximum):
        raise ValueError("cost energy is not invariant under supplied generators")
    return QuotientArchitecture(
        qubits=qubits,
        labels=labels,
        sizes=sizes,
        mixer=quotient_mixer(labels, sizes, qubits),
        orbit_energy=minimum,
    )


def evolve_quotient(
    architecture: QuotientArchitecture, gammas: np.ndarray, betas: np.ndarray
) -> QuotientState:
    coefficients = np.sqrt(architecture.sizes / architecture.labels.size).astype(
        np.complex128
    )
    for gamma, beta in zip(gammas, betas, strict=True):
        coefficients *= np.exp(-1j * float(gamma) * architecture.orbit_energy)
        coefficients = expm_multiply(
            (-1j * float(beta)) * architecture.mixer, coefficients
        )
    return QuotientState(architecture, np.asarray(coefficients))


def _factor_spectrum(factors: np.ndarray, metric: np.ndarray) -> dict:
    _, triangular = linalg.qr(
        factors, mode="economic", check_finite=False, overwrite_a=True
    )
    core = triangular @ metric @ triangular.conj().T
    values = linalg.eigvalsh(core, check_finite=False)
    values = values[np.argsort(np.abs(values))[::-1]]
    rank = int(np.count_nonzero(np.abs(values) > RANK_TOLERANCE))
    return {
        "numerical_rank": rank,
        "trace": float(values.sum(dtype=np.float64)),
        "trace_norm": float(np.abs(values).sum(dtype=np.float64)),
        "factor_columns": int(metric.shape[0]),
    }


def quotient_decision_spectrum(
    state_a: QuotientState,
    state_b: QuotientState,
    event_indices: np.ndarray,
    cut: int,
) -> dict:
    """Exact DCS spectrum using only orbit coefficient queries."""
    if state_a.architecture is not state_b.architecture:
        raise ValueError("states must share one compiled quotient architecture")
    qubits = state_a.architecture.qubits
    dimension = 1 << cut
    right_dimension = 1 << (qubits - cut)
    event_left, event_right = split_event_indices(event_indices, qubits, cut)
    prefixes = np.unique(event_left)
    suffixes = np.unique(event_right)
    if 2 * prefixes.size <= 4 * suffixes.size:
        support = np.zeros((dimension, prefixes.size), dtype=np.complex128)
        support[prefixes, np.arange(prefixes.size)] = 1.0
        contrast = np.empty_like(support)
        all_left = np.arange(dimension, dtype=np.int64)
        for column, prefix in enumerate(prefixes):
            selected_right = event_right[event_left == prefix]
            query = (
                all_left[:, None] * right_dimension + selected_right[None, :]
            )
            b_matrix = state_b.amplitudes(query)
            a_matrix = state_a.amplitudes(query)
            b_row = state_b.amplitudes(prefix * right_dimension + selected_right)
            a_row = state_a.amplitudes(prefix * right_dimension + selected_right)
            contrast[:, column] = (
                b_matrix @ b_row.conj() - a_matrix @ a_row.conj()
            )
        factors = np.concatenate((support, contrast), axis=1)
        count = prefixes.size
        metric = np.zeros((2 * count, 2 * count), dtype=np.complex128)
        metric[:count, count:] = 0.5 * np.eye(count)
        metric[count:, :count] = 0.5 * np.eye(count)
        method = "left-prefix"
    else:
        count = suffixes.size
        all_left = np.arange(dimension, dtype=np.int64)
        v_b = np.empty((dimension, count), dtype=np.complex128)
        v_a = np.empty_like(v_b)
        u_b = np.zeros_like(v_b)
        u_a = np.zeros_like(v_b)
        for column, suffix in enumerate(suffixes):
            query = all_left * right_dimension + suffix
            v_b[:, column] = state_b.amplitudes(query)
            v_a[:, column] = state_a.amplitudes(query)
            selected_left = event_left[event_right == suffix]
            selected_query = selected_left * right_dimension + suffix
            u_b[selected_left, column] = state_b.amplitudes(selected_query)
            u_a[selected_left, column] = state_a.amplitudes(selected_query)
        factors = np.concatenate((u_b, v_b, u_a, v_a), axis=1)
        metric = np.zeros((4 * count, 4 * count), dtype=np.complex128)
        eye = 0.5 * np.eye(count)
        metric[:count, count:2 * count] = eye
        metric[count:2 * count, :count] = eye
        metric[2 * count:3 * count, 3 * count:] = -eye
        metric[3 * count:, 2 * count:3 * count] = -eye
        method = "right-suffix"
    return {"factorization": method, **_factor_spectrum(factors, metric)}
